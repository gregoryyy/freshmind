import { readFile, writeFile } from "node:fs/promises";
import { parse } from "yaml";

// The YAML file is authoritative. Commit the generated module so the headless
// model/registry entry point can use the preset without importing a YAML parser.
const source = await readFile(new URL("../config/fm2014.types.yaml", import.meta.url), "utf8");
const notice = `/*!\n`
  + ` * Freshmind. Licensed under the Apache License, Version 2.0.\n`
  + ` * SPDX-License-Identifier: Apache-2.0\n`
  + ` * Copyright (c) 2002-2014 Gregor Heinrich.\n`
  + ` * Copyright (c) 2026 TypeScript port by Gregor Heinrich using Codex GPT-6.1.\n`
  + ` * See licenses/LICENSE-APACHE-2.0 for the license text.\n`
  + ` */\n\n`;
const module = notice + `// Generated by npm run sync:fm-config from config/fm2014.types.yaml.\n`
  + `import type { TypeConfiguration } from "./types.js";\n`
  + `export const freshmind2014Configuration = ${JSON.stringify(parse(source), null, 2)} satisfies TypeConfiguration;\n`;
await writeFile(new URL("../src/fm/config/fm2014.ts", import.meta.url), module);
await writeFile(new URL("../docs/design/examples/fm2014.types.yaml", import.meta.url), source);
