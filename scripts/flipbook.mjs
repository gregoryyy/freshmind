function escape(value) { return value.replace(/[&<>"']/g, char => ({"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"})[char]); }
const ownedFile = name => ["README.md", "index.html", "manifest.json"].includes(name) || /^\d{2}-[a-z0-9-]+\.png$/.test(name);

/** Refuses unrelated output directories; regeneration removes only files named by an earlier manifest. */
async function previousOutput(output) {
  let files;
  try { files = await readdir(output); } catch (error) { if (error.code === "ENOENT") return []; throw error; }
  if (files.length === 0) return [];
  let previous;
  try { previous = JSON.parse(await readFile(join(output, "manifest.json"), "utf8")); }
  catch { throw new Error(`Output is not a generated Freshmind flipbook: ${output}`); }
  if (previous.format !== "freshmind-flipbook" || previous.version !== 1 || !Array.isArray(previous.files) || !previous.files.every(name => typeof name === "string" && ownedFile(name)))
    throw new Error(`Invalid flipbook manifest: ${output}`);
  return previous.files;
}

