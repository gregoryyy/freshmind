function chapterIndex(shots) {
  const chapters = new Map();
  for (const shot of shots) {
    if (!shot.chapter) continue;
    const chapter = chapters.get(shot.chapter);
    if (chapter) chapter.count++;
    else chapters.set(shot.chapter, {title: shot.chapter, id: shot.id, count: 1});
  }
  return [...chapters.values()];
}

