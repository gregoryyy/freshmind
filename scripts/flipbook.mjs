/** Serves its own production build, captures every step, then publishes a completed walkthrough. */
async function main() {
  if(!["browser","rfc-showcase","search"].includes(values.tour))throw new Error("--tour must be browser, rfc-showcase or search");
  const port = Number(values.port);
  if (!/^\d+$/.test(values.port) || !Number.isInteger(port) || port < 0 || port > 65535) throw new Error("--port must be an integer in 0–65535 (0 selects an available port)");
  const ids = new Set();
  for (const step of tour) {
    if (!/^[a-z0-9-]+$/.test(step.id) || ids.has(step.id)) throw new Error("Invalid or duplicate tour step ID: " + step.id);
    ids.add(step.id);
  }
  const output = resolve(root, values.output??(showcase?"docs/rfc-showcase":search?"docs/search-walkthrough":"docs/flipbook")), previous = await previousOutput(output);
  await access(join(root, "demo-dist/index.html")).catch(() => { throw new Error("Production build missing: run just flipbook or just build-demo first"); });
  const staging = await mkdtemp(join(tmpdir(), "fm4-flipbook-"));
  let server, browser;
  const cleanup = async () => {
    await browser?.close();
    if (server) await new Promise((done, reject) => server.httpServer.close(error => error ? reject(error) : done()));
    await rm(staging, {recursive: true, force: true});
  };
  const interrupt = () => { void cleanup().finally(() => process.exit(130)); };
  process.once("SIGINT", interrupt); process.once("SIGTERM", interrupt);
  try {
    server = await preview({root, logLevel: "error", preview: {host: "127.0.0.1", port, strictPort: true, open: false}});
    const address = server.httpServer.address();
    const base = `http://127.0.0.1:${address.port}`;
    browser = await chromium.launch({channel: values.channel, headless: true});
    const context = await browser.newContext({viewport, deviceScaleFactor: 1, reducedMotion: "reduce", colorScheme: "light"});
    const page = await context.newPage(), errors = [];
    page.setDefaultTimeout(15000); page.setDefaultNavigationTimeout(30000);
    page.on("pageerror", error => errors.push(error.message));
    await page.addInitScript(() => {
      let seed = 0x1234abcd;
      Math.random = () => { seed = (Math.imul(1664525, seed) + 1013904223) >>> 0; return seed / 4294967296; };
    });
    const advance = async batches => {
      await page.evaluate(async count => {
        const panel = window.graphBrowser || window.freshmindBrowser;
        panel.fastFinishAnimation(); await panel.getLocalityUtils().whenIdle();
        panel.tgLayout.tick(count); panel.repaint();
      }, batches);
    };
    const open = async path => {
      await page.goto(base + path);
      await page.waitForFunction(() => Boolean(window.graphBrowser || window.freshmindBrowser));
      const motion = page.locator("#motion");
      if (["Pause motion", "Pause layout"].includes((await motion.textContent()).trim())) await motion.click();
      await advance(0);
    };
    const shots = [];
    for (const [index, step] of tour.entries()) {
      await step.run({page, open, advance});
      await page.evaluate(async () => { await document.fonts.ready; });
      // Wait for browser paint rather than relying on a fixed layout/animation delay.
      await page.evaluate(() => new Promise(done => requestAnimationFrame(() => requestAnimationFrame(done))));
      if (errors.length) throw new Error(`Step ${step.id}: ${errors.join("; ")}`);
      const file = `${String(index + 1).padStart(2, "0")}-${step.id}.png`;
      await page.screenshot({path: join(staging, file), fullPage: true, animations: "disabled"});
      shots.push({id: step.id, title: step.title, caption: step.caption, ...(step.chapter?{chapter:step.chapter}:{}), file});
      console.log(`[flipbook] ${file}`);
    }
    const files = [...shots.map(shot => shot.file), "README.md", "index.html", "manifest.json"];
    await writeFile(join(staging, "README.md"), markdown(shots));
    await writeFile(join(staging, "index.html"), html(shots));
    await writeFile(join(staging, "manifest.json"), JSON.stringify({format: "freshmind-flipbook", version: 1, build: "demo-dist", source, viewport, browser: await browser.version(), files, steps: shots}, null, 2) + "\n");
    await mkdir(dirname(output), {recursive: true}); await mkdir(output, {recursive: true});
    for (const file of files) await copyFile(join(staging, file), join(output, file));
    for (const file of previous) if (!files.includes(file)) await unlink(join(output, file)).catch(error => { if (error.code !== "ENOENT") throw error; });
    console.log(`[flipbook] Wrote ${shots.length} steps to ${output}/index.html and README.md`);
  } finally {
    process.removeListener("SIGINT", interrupt); process.removeListener("SIGTERM", interrupt);
    await cleanup();
  }
}

if (values.help) {
  console.log("Usage: just flipbook [--tour browser|rfc-showcase|search] [--output DIRECTORY] [--port PORT] [--channel chrome|chromium|msedge]\nDefaults: browser tour in docs/flipbook, rfc-showcase in docs/rfc-showcase, search in docs/search-walkthrough; an available local port, Google Chrome. Outputs: PNGs, README.md, index.html and manifest.json.");
} else {
  try { await main(); }
  catch (error) { console.error("[flipbook] " + error.message); process.exitCode = 1; }
}
